#!/usr/bin/env node
/**
 * Commit-message attribution guard — CLAUDE.md, "Project Identity & Git Attribution".
 *
 * WHY THIS EXISTS. The policy is explicit and the owner enforced it by hand once: rules 1
 * and 2 forbid an AI agent, coding tool or bot being named as an author or co-author, and
 * forbid a generated-by tag, signature line or automated footer — naming the exact strings
 * — and no `commit-msg` hook or template in this repository adds one (rule 7). What the
 * repository never had was anything that could FAIL when one was added anyway. It happened
 * again the other way round: six commits on the AI-1..AI-6 branch arrived carrying
 * `🤖 Generated with Codebuff` and `Co-Authored-By: Codebuff <noreply@codebuff.com>`,
 * including the one already published as PR #74's head. `main` was clean, so a normal merge
 * of that pull request would have written them into the project's permanent history. This
 * script is the missing check.
 *
 * WHAT IT CHECKS. The commit messages this event introduces — `BASE_SHA..HEAD`, where the
 * workflow supplies the pull request's base commit or a push's `before` — for a line that IS
 * one of the forbidden forms. Nothing else in the message is examined.
 *
 * THE PATTERNS ARE LINE-ANCHORED, AND THAT IS LOAD-BEARING. A trailer is a line of its own;
 * a sentence that discusses the rule is not. Without the anchor, this file's own commit
 * message — and the paragraph above — would fail the check, which is precisely the bug
 * §27BP records in another guard ("a guard that failed on its own documentation"). The
 * self-test below pins both directions so the distinction cannot be quietly lost.
 *
 * THE OWNER'S OWN TRAILER AND DEPENDABOT'S ARE DELIBERATELY ALLOWED. `Co-Authored-By:`
 * naming a human — the repository's configured identity — and Dependabot's own bot trailer
 * are both legitimate; the roadmap keeps the Dependabot ones on purpose. Only the named
 * tools are refused.
 *
 * EXIT CODES, kept apart for the reason §27BP gives — exit 1 is a claim about the commits,
 * so it may only ever mean a trailer was found:
 *
 *   0  every commit in the range was read and none carries a forbidden trailer
 *   1  a forbidden trailer was found (the offending commits are printed)
 *   2  NOT VERIFIED — the range could not be resolved, e.g. a shallow checkout that does
 *      not contain the base commit, so nothing was checked
 *
 * The self-test runs first on every invocation, as `scripts/check-secrets.mjs` does.
 */
import { execFileSync } from 'node:child_process';

/** The forbidden forms, each with the rule it comes from. Line-anchored — see the header. */
const FORBIDDEN_LINES = [
  {
    // "🤖 Generated with Codebuff" and "Generated with Claude Code", with or without the
    // emoji, on a line of its own.
    re: /^\s*(?:\u{1F916}\s*)?Generated with (?:Codebuff|Claude Code)\s*$/u,
    rule: 'rule 2 — no generated-by tag, signature line or automated footer',
  },
  {
    re: /^\s*Generated by (?:Claude|Codebuff)\s*$/u,
    rule: 'rule 2 — no generated-by tag, signature line or automated footer',
  },
  {
    re: /^\s*Made with \S.*$/u,
    rule: 'rule 2 — no generated-by tag, signature line or automated footer',
  },
  {
    re: /^\s*Co-Authored-By:\s*(?:Codebuff|Claude Code|Claude|Anthropic)\b.*$/iu,
    rule: 'rule 1 — no co-author trailer for an AI agent, coding tool or bot',
  },
];

/** Lines that must NOT be treated as attribution. */
const ALLOWED_LINES = [
  'Co-Authored-By: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>',
  'Co-Authored-By: Jeffern <jeffernmalinaoqwe@gmail.com>',
  'A sentence may discuss Generated with Codebuff without being a trailer.',
  'Body text mentioning Co-Authored-By: Codebuff as an example is not a trailer line.',
];

/**
 * Rule 4 has a second half the message cannot show: the commit's AUTHOR AND COMMITTER
 * fields are the primary place a tool gets named as an author, and a message-only check
 * would miss a commit made *as* `Claude Code <noreply@anthropic.com>` with a clean body.
 * The named tools are matched as substrings of the name or the address, because those
 * fields are short and an agent picks its own label.
 */
const FORBIDDEN_IDENTITIES = [/codebuff/i, /anthropic/i, /claude/i, /copilot/i, /cursor/i];

/**
 * The one bot identity that is legitimate here. Dependabot commits real dependency
 * updates, it is not a coding tool, and the roadmap deliberately KEEPS its trailers
 * (§27AS). Verified before allowing it: it is the only bot-shaped identity in `main`'s
 * history, so this allowlist is a fact about the repository rather than a convenience.
 */
const ALLOWED_IDENTITIES = [/^dependabot\[bot\]/i];

/** The forbidden tool named by an identity field, or `null`. */
function forbiddenIdentity(name, email) {
  const value = `${name} <${email}>`;
  if (ALLOWED_IDENTITIES.some((re) => re.test(name))) return null;
  for (const re of FORBIDDEN_IDENTITIES) if (re.test(value)) return re.source;
  return null;
}

/** The one matcher both the scan and the self-test use. */
function forbiddenRuleFor(line) {
  for (const entry of FORBIDDEN_LINES) if (entry.re.test(line)) return entry.rule;
  return null;
}

function selfTest() {
  const controls = [];
  const SAMPLE_BAD = [
    '🤖 Generated with Codebuff',
    'Generated with Codebuff',
    'Generated with Claude Code',
    'Generated by Claude',
    'Co-Authored-By: Codebuff <noreply@codebuff.com>',
    'Co-Authored-By: Claude Code <noreply@anthropic.com>',
    '  Co-Authored-By: Anthropic <x@y.z>',
  ];
  for (const line of SAMPLE_BAD) {
    controls.push([`must-fire: ${JSON.stringify(line)}`, forbiddenRuleFor(line) !== null]);
  }
  for (const line of ALLOWED_LINES) {
    controls.push([`must-not-fire: ${JSON.stringify(line)}`, forbiddenRuleFor(line) === null]);
  }
  // The identity half, both directions.
  for (const [name, email] of [
    ['Claude Code', 'noreply@anthropic.com'],
    ['Codebuff', 'noreply@codebuff.com'],
    ['Cursor Agent', 'agent@cursor.com'],
    ['GitHub Copilot', 'copilot@github.com'],
  ]) {
    controls.push([`must-fire identity: ${name} <${email}>`, forbiddenIdentity(name, email) !== null]);
  }
  for (const [name, email] of [
    ['jeffernzxc', 'jeffernmalinaoqwe@gmail.com'],
    ['dependabot[bot]', '49699333+dependabot[bot]@users.noreply.github.com'],
  ]) {
    controls.push([`must-not-fire identity: ${name}`, forbiddenIdentity(name, email) === null]);
  }
  const failed = controls.filter(([, ok]) => !ok);
  if (failed.length) {
    console.error('[attribution] SELF-TEST FAILED — the guard cannot be trusted:');
    for (const [label] of failed) console.error(`[attribution]   ${label}`);
    process.exit(2);
  }
  return controls.length;
}

function git(args) {
  return execFileSync('git', args, { encoding: 'utf8' });
}

/**
 * Whether `ref` resolves to a commit here. Git's own complaint is swallowed on purpose: the
 * guard prints its own sentence, and a raw `fatal: Not a valid object name …` next to it reads
 * as though the guard itself broke.
 */
function commitExists(ref) {
  try {
    execFileSync('git', ['rev-parse', '--verify', '--quiet', `${ref}^{commit}`], {
      stdio: ['ignore', 'ignore', 'ignore'],
    });
    return true;
  } catch {
    return false;
  }
}

/** A ref as a reader should see it: a branch name in full, a raw SHA shortened. */
function refLabel(ref) {
  return /^[0-9a-f]{40}$/i.test(ref) ? ref.slice(0, 10) : ref;
}

function main() {
  const controlCount = selfTest();
  console.log(
    `[attribution] self-test: ${controlCount} control(s) passed ` +
      `(${FORBIDDEN_LINES.length} forbidden form(s), ${ALLOWED_LINES.length} allowed line(s))`,
  );

  const base = (process.env.BASE_SHA ?? '').trim();
  const useRange = base && !/^0+$/.test(base);

  let shas;
  if (useRange) {
    if (!commitExists(base)) {
      console.error(
        `[attribution] NOT VERIFIED (exit 2) — the base commit ${refLabel(base)} is not in this ` +
          'checkout, so no commit message was read. A shallow clone is the usual cause; the ' +
          'workflow checks out the full history.',
      );
      process.exit(2);
    }
    try {
      shas = git(['rev-list', `${base}..HEAD`]).split('\n').filter(Boolean);
      // The label is the ref a reader recognises — a branch name in full, a SHA shortened —
      // because "origin/mai" is a worse answer than "not telling them" would be.
      console.log(`[attribution] range: ${refLabel(base)}..HEAD — ${shas.length} commit(s) to read`);
    } catch (err) {
      console.error(`[attribution] NOT VERIFIED (exit 2) — could not list the range: ${err.message}`);
      process.exit(2);
    }
  } else {
    // No base to compare against (a manual run, or an event that has none). Checking HEAD
    // alone would be a silent half-measure, so it is stated rather than implied.
    shas = git(['rev-list', '-1', 'HEAD']).split('\n').filter(Boolean);
    console.log('[attribution] no BASE_SHA — checking HEAD only (say so, do not imply the branch was read)');
  }

  const offenders = [];
  const identities = [];
  for (const sha of shas) {
    const message = git(['log', '-1', '--format=%B', sha]);
    for (const line of message.split('\n')) {
      const rule = forbiddenRuleFor(line);
      if (rule) offenders.push({ sha, line: line.trim(), rule });
    }
    // `%an`/`%ae` and `%cn`/`%ce` — the author AND the committer, since either field can
    // name a tool and they are not always the same person.
    const [an, ae, cn, ce] = git(['log', '-1', '--format=%an%x00%ae%x00%cn%x00%ce', sha]).split('\u0000');
    for (const [field, name, email] of [
      ['author', an, ae],
      ['committer', cn, ce],
    ]) {
      const named = forbiddenIdentity(name, email);
      if (named) identities.push({ sha, field, name, email, named });
    }
  }

  if (offenders.length || identities.length) {
    const commits = new Set([...offenders.map((o) => o.sha), ...identities.map((i) => i.sha)]);
    console.error(
      `[attribution] FAIL — ${offenders.length + identities.length} forbidden attribution finding(s) in ${commits.size} commit(s):`,
    );
    for (const { sha, line, rule } of offenders) {
      console.error(`[attribution]   ${sha.slice(0, 10)}  ${JSON.stringify(line)}`);
      console.error(`[attribution]     ${rule}`);
    }
    for (const { sha, field, name, email, named } of identities) {
      console.error(`[attribution]   ${sha.slice(0, 10)}  ${field}: ${name} <${email}>`);
      console.error(`[attribution]     rule 1/4 — a tool is not an author (matched ${named})`);
    }
    console.error(
      '[attribution] CLAUDE.md: the only identity that may appear anywhere in a commit is the owner’s own.',
    );
    process.exit(1);
  }

  console.log('[attribution] every commit read is free of a forbidden attribution trailer.');
}

main();
