const { ObjectId } = mongoose.Types;

// The value must be unique across PARALLEL test processes, not merely within
// one. `node --test` runs every file in its own process, and the sequence
// counter below is per-process, so a bare `<prefix>-<Date.now()>-<seq>` can be
// generated by two files in the same millisecond and collide — which is what
// made `registerOwner` intermittently fail with a 409 EMAIL_IN_USE. Including
// `process.pid`, unique among live processes, makes the value process-safe;
// prefix, timestamp and sequence keep their existing roles and order.
let _seq = 0;
function next(prefix) {
  _seq += 1;
  return `${prefix}-${process.pid}-${Date.now()}-${_seq}`;
}

export function uniqueEmail(prefix = 'p04') {
  return `${next(prefix)}@example.com`;
}

export function uniqueName(prefix) {
  return next(prefix);
}

/** Starts the shipped app (real routers + middleware) on an ephemeral port. */
export async function startServer() {
  const dbOk = await ensureDb();
  if (!dbOk) return { dbOk: false, baseUrl: null, server: null };
  const server = app.listen(0);
  await new Promise((resolve) => server.once('listening', resolve));
  return { dbOk: true, baseUrl: `http://127.0.0.1:${server.address().port}`, server };
}

/** fetch wrapper over the running server. */
export function makeApi(baseUrl) {
  return async function api(method, path, { token, body } = {}) {
    const headers = { 'content-type': 'application/json' };
    if (token) headers.authorization = `Bearer ${token}`;
    const res = await fetch(`${baseUrl}${path}`, {
      method,
      headers,
      body: body ? JSON.stringify(body) : undefined,
    });
    let json;
    try {
      json = await res.json();
    } catch {
      json = null;
    }
    return { status: res.status, json };
  };
}

/**
 * Writes ONE value onto a raw column of the given rows (Phase 20A / 20C).
 *
 * `timestamps: true` owns createdAt / updatedAt, so a deliberate tie — several
 * rows sharing one sort value — has to be stamped onto the collection directly.
 *
 * The write is then read back and asserted. This is not belt-and-braces: the raw
 * collection API does NOT cast, so a string `_id` would match nothing and leave
 * the rows with their natural, already-distinct timestamps. A pagination suite
 * would then "pass" against unfixed code because there was never a tie to page
 * over.
 */
export async function stampField(model, ids, field, value) {
  const oids = ids.map((id) => new ObjectId(id));
  await model.collection.updateMany({ _id: { $in: oids } }, { $set: { [field]: value } });

  const stamped = await model.find({ _id: { $in: oids } }).select(field).lean();
  assert.equal(stamped.length, ids.length, `stamp: expected ${ids.length} rows to exist`);
  for (const doc of stamped) {
    assert.equal(
      new Date(doc[field]).getTime(),
      value.getTime(),
      `stamp: ${field} did not take effect on ${doc._id}`
    );
  }
}

/**
 * Tracks created users/businesses and deletes them (plus every child document)
 * so repeated test runs leave the shared dev database clean.
 */
export function createTracker(dbOk) {
  const businessIds = [];
  const userIds = [];
  return {
    trackBusiness(id) {
      if (id) businessIds.push(String(id));
    },
    trackUser(id) {
      if (id) userIds.push(String(id));
    },
    businessCount() {
      return businessIds.length;
    },
    async cleanup() {
      if (!dbOk) return;
      const biz = businessIds.map((x) => new ObjectId(x));
      const users = userIds.map((x) => new ObjectId(x));
      const db = mongoose.connection.db;
      const deleteByBusiness = async (collection) => {
        if (!biz.length) return;
        try {
          await db.collection(collection).deleteMany({ businessId: { $in: biz } });
        } catch {
          /* best effort */
        }
      };
      await deleteByBusiness('inventory_transactions');
      await deleteByBusiness('inventory');
      await deleteByBusiness('products');
      await deleteByBusiness('categories');
      await deleteByBusiness('locations');
      await deleteByBusiness('audit_logs');
      await deleteByBusiness('ai_turn_metrics');
      await deleteByBusiness('suppliers');
      await deleteByBusiness('purchase_orders');
      // AI conversations/messages have no businessId on the message, so remove
      // messages by the conversations owned by these businesses first.
      if (biz.length) {
        try {
          const convs = await db
            .collection('ai_conversations')
            .find({ businessId: { $in: biz } }, { projection: { _id: 1 } })
            .toArray();
          const cids = convs.map((c) => c._id);
          if (cids.length) {
            await db.collection('ai_messages').deleteMany({ conversationId: { $in: cids } });
          }
          await db.collection('ai_conversations').deleteMany({ businessId: { $in: biz } });
        } catch {
          /* best effort */
        }
      }
      await deleteByBusiness('businesses');
      if (users.length) {
        try {
          // Phase 26A: sessions belong to a user, not a business, so they are
          // removed by userId alongside the users themselves. Without this the
          // rows would linger until their TTL index expires.
          await db.collection('sessions').deleteMany({ userId: { $in: users } });
        } catch {
          /* best effort */
        }
        try {
          // Phase 26B-2: password-reset tokens belong to a user, not a business,
          // so they are removed by userId alongside the sessions and the user
          // itself. Without this the rows would linger until their TTL expires.
          await db.collection('password_reset_tokens').deleteMany({ userId: { $in: users } });
        } catch {
          /* best effort */
        }
        try {
          await db.collection('users').deleteMany({ _id: { $in: users } });
        } catch {
          /* best effort */
        }
      }
    },
  };
}

/**
 * Registers a brand-new business + OWNER over the real /api/auth/register and
 * returns an authenticated owner session.
 */
export async function registerOwner(api, tracker) {
  const email = uniqueEmail('owner');
  const password = 'Password123!';
  const reg = await api('POST', '/api/auth/register', {
    body: { businessName: uniqueName('Biz'), name: uniqueName('Owner'), email, password },
  });
  if (reg.status !== 201) {
    throw new Error(`registerOwner failed: ${reg.status} ${JSON.stringify(reg.json)}`);
  }
  tracker.trackBusiness(reg.json.business.id);
  tracker.trackUser(reg.json.user.id);
  const login = await api('POST', '/api/auth/login', { body: { email, password } });
  if (login.status !== 200) {
    throw new Error(`registerOwner login failed: ${login.status} ${JSON.stringify(login.json)}`);
  }
  return {
    token: login.json.token,
    userId: reg.json.user.id,
    businessId: reg.json.business.id,
  };
}

/**
 * Mints a usable access token for a user that already exists in the database:
 * a fresh session id is signed into the token AND written as a session row, so
 * the token passes requireAuth's Phase 26A session check.
 *
 * Since 26A a token without a live session is rejected, so any fixture that used
 * to call signAccessToken(user._id) directly must go through here instead. The
 * row is tracked for cleanup by userId (sessions carry no businessId).
 */
export async function issueSessionToken(userId, { deviceLabel } = {}) {
  const jti = newSessionId();
  const token = signAccessToken(userId, jti);
  await Session.create({
    userId: new ObjectId(userId),
    jti,
    ...(deviceLabel ? { deviceLabel } : {}),
    // Mirrors the real login path (AUTH-02): the row carries the session's own
    // 14-day ABSOLUTE cap, never the token's `exp`. The token expires in ~1h;
    // the session it names lives for 14 days.
    expiresAt: new Date(Date.now() + SESSION_ABSOLUTE_CAP_MS),
  });
  return token;
}

/**
 * Creates a user directly in the database with the given role so role-guarded
 * endpoints can be exercised as ADMIN/MANAGER/STAFF. Reuses an existing business
 * when businessId is given. (Phase 14A added the /api/users management routes;
 * this helper still writes directly to seed fixture roles like the OWNER, which
 * the management API intentionally cannot create.)
 */
export async function makeRoleUser({ role, businessId }, tracker) {
  let bid = businessId;
  if (!bid) {
    const business = await Business.create({ name: uniqueName('Biz') });
    bid = String(business._id);
    tracker.trackBusiness(bid);
  }
  const user = await User.create({
    businessId: new ObjectId(bid),
    name: uniqueName(role),
    email: uniqueEmail(role.toLowerCase()),
    passwordHash: bcrypt.hashSync('Password123!', 10),
    role,
    status: 'ACTIVE',
  });
  tracker.trackUser(String(user._id));
  return {
    userId: String(user._id),
    businessId: bid,
    token: await issueSessionToken(user._id),
  };
}

